#!/usr/bin/env python3
"""PICduino Arduino IDE 2.x build orchestrator for a documented .ino subset.

This intentionally does not claim general C++ or Arduino-library compatibility.
"""
from __future__ import annotations
import argparse, os, re, shutil, subprocess, sys
from pathlib import Path

VERSION = "0.4.0"
UNSUPPORTED = [
    (r'\b(class|template|namespace|new|delete|try|catch|throw|virtual|operator)\b', "C++ classes/templates/exceptions are not supported"),
    (r'\b(auto)\s+[A-Za-z_]\w*\s*=', "C++ type inference (auto) is not supported"),
    (r'\[[^\]]*\]\s*\([^)]*\)\s*\{', "lambda expressions are not supported"),
]
FUNC_RE = re.compile(r'(?m)^\s*(?:static\s+)?(?:void|bool|char|short|int|long|unsigned(?:\s+(?:char|short|int|long))?|float|double|uint8_t|uint16_t|uint32_t|int8_t|int16_t|int32_t)\s+([A-Za-z_]\w*)\s*\(([^;{}]*)\)\s*\{')

class BuildError(RuntimeError): pass

def run(cmd, cwd=None):
    print("+", subprocess.list2cmdline([str(x) for x in cmd]))
    p = subprocess.run([str(x) for x in cmd], cwd=str(cwd) if cwd else None)
    if p.returncode:
        raise BuildError(f"command failed with exit code {p.returncode}")

def translate_sketch(sketch: Path, build_dir: Path, core_dir: Path) -> Path:
    ino_files = sorted(sketch.parent.glob("*.ino"), key=lambda p: (p.name != sketch.name, p.name.lower()))
    if not ino_files: raise BuildError(f"no .ino files found beside {sketch}")
    pieces=[]
    for path in ino_files:
        source=path.read_text(encoding="utf-8-sig")
        # Ignore comments and string/character literals when screening for C++-only
        # constructs, so words like "class" in prose do not cause false positives.
        screened = re.sub(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', ' ', source, flags=re.S)
        for pattern, message in UNSUPPORTED:
            if re.search(pattern, screened): raise BuildError(f"{path.name}: {message}; remove this construct or use a C-compatible alternative")
        # Translate the implemented Arduino Serial subset to C functions.
        # This is deliberately a small supported API, not general C++ support.
        source = re.sub(r'\bSerial\s*\.\s*begin\s*\(', 'serial_begin(', source)
        source = re.sub(r'\bSerial\s*\.\s*println\s*\(', 'serial_println(', source)
        source = re.sub(r'\bSerial\s*\.\s*print\s*\(', 'serial_print(', source)
        source = re.sub(r'\bSerial\s*\.\s*available\s*\(', 'serial_available(', source)
        source = re.sub(r'\bSerial\s*\.\s*read\s*\(', 'serial_read(', source)
        # Keep user includes except Arduino.h, which maps to PICduino's core API.
        source=re.sub(r'^\s*#\s*include\s*[<"]Arduino\.h[>"]\s*$', '', source, flags=re.M)
        # Remove common C++-only casts and namespaces are rejected above; this is not a general parser.
        pieces.append(f"\n/* Source: {path.name} */\n" + source)
    # Option A deliberately supports C-compatible sketches only. Include plain C
    # helper files from the sketch directory in the same translation unit; this is
    # not a general Arduino library build system.
    for cfile in sorted(sketch.parent.glob("*.c")):
        pieces.append(f"\n/* C helper: {cfile.name} */\n" + cfile.read_text(encoding="utf-8-sig"))
    combined="\n".join(pieces)
    if not re.search(r'\bvoid\s+setup\s*\(\s*void?\s*\)', combined):
        # also accept void setup() exactly; regex above tolerates whitespace.
        if not re.search(r'\bvoid\s+setup\s*\(\s*\)', combined): raise BuildError("sketch must define void setup()")
    if not re.search(r'\bvoid\s+loop\s*\(\s*\)', combined): raise BuildError("sketch must define void loop()")
    # C-compatible prototype generation for top-level function definitions.
    prototypes=[]
    for m in FUNC_RE.finditer(combined):
        name,args=m.group(1),m.group(2).strip()
        if name in {"setup", "loop"}: prototypes.append(f"void {name}(void);")
        else: prototypes.append(f"{combined[m.start():m.start()+m.group(0).find(name)].strip()} {name}({args or 'void'});")
    build_dir.mkdir(parents=True, exist_ok=True)
    generated=build_dir / (sketch.stem + ".picduino.c")
    core_c=core_dir / "picduino_core.c"
    core_h=core_dir / "Arduino.h"
    # Amalgamation intentionally keeps the first implementation single-translation-unit.
    generated.write_text(
        "/* Generated by PICduino build tool. Do not edit. */\n"
        f'#include "{core_h.as_posix()}"\n'
        + "\n".join(dict.fromkeys(prototypes)) + "\n"
        + f'#include "{core_c.as_posix()}"\n'
        + "\n/* ---- translated sketch ---- */\n" + combined + "\n",
        encoding="utf-8")
    print(f"PICduino: translated {len(ino_files)} .ino file(s) -> {generated}")
    return generated

def locate_tool(name: str, explicit: str | None, fallback: Path) -> Path:
    if explicit:
        p=Path(explicit).expanduser().resolve()
        if not p.is_file(): raise BuildError(f"{name} not found: {p}")
        return p
    if fallback.is_file(): return fallback.resolve()
    raise BuildError(f"{name} not found at {fallback}; pass its path explicitly")

def build(args):
    sketch=Path(args.sketch).expanduser().resolve()
    if not sketch.is_file() or sketch.suffix.lower() != ".ino": raise BuildError("sketch must be an existing .ino file")
    platform=Path(args.platform).expanduser().resolve() if args.platform else Path(__file__).resolve().parent.parent
    core_dir=platform/"cores"/"picduino"
    for required in (core_dir/"Arduino.h", core_dir/"picduino_core.c", platform/"variants"/"pic18f4550"/"pins_arduino.h"):
        if not required.is_file(): raise BuildError(f"required PICduino core file missing: {required}")
    build_dir=Path(args.build_dir).expanduser().resolve() if args.build_dir else sketch.parent/"build-picduino"
    build_dir.mkdir(parents=True, exist_ok=True)
    generated=translate_sketch(sketch, build_dir, core_dir)
    compiler=locate_tool("PICduino compiler wrapper", args.compiler, platform/"tools"/"picduino_compiler.py")
    # Remove outputs from previous builds so an unsuccessful XC8 invocation can
    # never leave a stale HEX that looks like a successful current build.
    for stale in (build_dir/(generated.stem+".hex"), build_dir/(sketch.stem+".hex"), build_dir/(sketch.name+".hex")):
        try: stale.unlink()
        except FileNotFoundError: pass
    cmd=[sys.executable, compiler, "-c", generated, "-codeoffset", args.codeoffset, "--output-dir", build_dir]
    if args.xc8: cmd += ["--xc8", args.xc8]
    if args.mdfp: cmd += ["--mdfp", args.mdfp]
    if args.optimization: cmd += ["-O", args.optimization]
    run(cmd, cwd=build_dir)
    raw_hex=build_dir/(generated.stem+".hex")
    if not raw_hex.is_file() or raw_hex.stat().st_size == 0: raise BuildError(f"compiler did not produce expected HEX: {raw_hex}")
    hexfile=build_dir/(sketch.stem+".hex")
    shutil.copy2(raw_hex, hexfile)
    # Arduino IDE 2.x may pass the sketch filename (including .ino) into
    # {build.project_name}; provide that exact alias for its upload recipe.
    ide_hexfile = build_dir / (sketch.name + ".hex")
    shutil.copy2(hexfile, ide_hexfile)
    print(f"PICduino BUILD SUCCESS: {hexfile}")
    print(f"PICduino IDE HEX alias: {ide_hexfile}")
    if args.command == "upload":
        uploader=locate_tool("PICduino uploader", args.uploader, platform/"tools"/"pic18f4550_uploader.py")
        up=[sys.executable, uploader, str(hexfile)]
        if args.port: up += ["--port", args.port]
        if args.no_reset: up += ["--no-reset"]
        run(up, cwd=build_dir)

def doctor(args):
    platform=Path(args.platform).expanduser().resolve() if args.platform else Path(__file__).resolve().parent.parent
    print(f"PICduino build tool {VERSION}\nPlatform: {platform}\nPython: {sys.executable}")
    failures=[]
    for rel in ["boards.txt","platform.txt","cores/picduino/Arduino.h","cores/picduino/picduino_core.c","variants/pic18f4550/pins_arduino.h","tools/picduino_compiler.py","tools/pic18f4550_uploader.py"]:
        p=platform/rel; ok=p.is_file(); print(f"{'OK' if ok else 'MISSING'}  {rel}")
        if not ok: failures.append(rel)
    try:
        import serial  # noqa
        print("OK  pyserial")
    except Exception:
        print("MISSING  pyserial (install with: python -m pip install pyserial)"); failures.append("pyserial")
    xc8=args.xc8 or shutil.which("xc8-cc")
    print(("OK  XC8: "+str(xc8)) if xc8 else "CHECK  XC8 not found on PATH (the compiler wrapper also searches common Windows install locations)")
    if failures: raise BuildError("doctor found missing prerequisites: "+", ".join(failures))
    print("Static prerequisite check passed. This does not test a physical PIC or bootloader.")

def preproc(args):
    """Provide a source snapshot for Arduino Builder's sketch preprocessor stage.

    This is intentionally a limited C-compatible-sketch path: it preserves the
    sketch text so Builder can generate its merged/prototype file. Real translation
    and XC8 compilation occur later in the build command.
    """
    if len(args) != 2:
        raise BuildError("preproc expects SOURCE_FILE OUTPUT_FILE")
    source = Path(args[0])
    output = Path(args[1])
    if not source.is_file():
        raise BuildError(f"preprocessor source not found: {source}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source.read_text(encoding="utf-8-sig"), encoding="utf-8")
    return 0

def noop(args):
    """Compatibility shim for Arduino builder preprocessing/dependency probes.

    Arduino Builder may append compiler-style flags (for example -MMD -MF file)
    to the configured command. Accept those flags rather than failing argument
    parsing. The actual PICduino compilation is performed by the combine recipe.
    """
    mf = None
    for i, value in enumerate(args):
        if value == "-MF" and i + 1 < len(args):
            mf = args[i + 1]
        elif value.startswith("-MF") and len(value) > 3:
            mf = value[3:]
    if mf:
        target = Path(mf)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("", encoding="utf-8")
    # The builder captures stdout for its temporary merged sketch. Emit a harmless
    # comment so the expected file is created; PICduino's combine recipe reads the
    # original .ino and performs its own documented-subset translation.
    print("/* PICduino preprocessing placeholder; real build is handled by picduino_build.py build. */")
    return 0

def main():
    p=argparse.ArgumentParser(description="PICduino build/upload orchestrator (Arduino-like C subset)")
    sub=p.add_subparsers(dest="command", required=True)
    sub.add_parser("noop", help="Arduino builder preprocessing compatibility shim")
    pre = sub.add_parser("preproc", help="Write source to Arduino Builder's preprocessed output path")
    pre.add_argument("source")
    pre.add_argument("output")
    for name in ("build","upload"):
        s=sub.add_parser(name); s.add_argument("sketch"); s.add_argument("--platform"); s.add_argument("--build-dir"); s.add_argument("--compiler"); s.add_argument("--xc8"); s.add_argument("--mdfp"); s.add_argument("--optimization",default=None); s.add_argument("--codeoffset",default="0x1000")
        if name=="upload": s.add_argument("--port",help="serial port selected in Arduino IDE, e.g. COM6"); s.add_argument("--uploader"); s.add_argument("--no-reset",action="store_true")
    d=sub.add_parser("doctor"); d.add_argument("--platform"); d.add_argument("--xc8")
    a, unknown=p.parse_known_args()
    try:
        if a.command=="doctor": doctor(a)
        elif a.command=="noop": return noop(sys.argv[2:])
        elif a.command=="preproc": return preproc([a.source, a.output])
        else:
            if unknown:
                raise BuildError("unexpected arguments: " + " ".join(unknown))
            build(a)
    except (BuildError, OSError, UnicodeError) as e: print(f"PICduino ERROR: {e}",file=sys.stderr); return 1
    return 0
if __name__=="__main__": sys.exit(main())
